-- ==============================================================================
-- Supabase Schema for VoltaConnext Dashboard
-- Run this in Supabase Dashboard -> SQL Editor
-- ==============================================================================

-- 1. Charging Data Table (Stores all raw sessions)
CREATE TABLE IF NOT EXISTS public.charging_data (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date DATE NOT NULL,
    charger_name TEXT NOT NULL,
    charger_head TEXT,
    vcard TEXT,
    start_time TIMESTAMP WITH TIME ZONE,
    stop_time TIMESTAMP WITH TIME ZONE,
    durations TEXT,
    energy_kwh NUMERIC(10, 2) DEFAULT 0,
    revenue_baht NUMERIC(12, 2) DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Indexes for lightning-fast queries
CREATE INDEX IF NOT EXISTS idx_charging_data_date ON public.charging_data(date);
CREATE INDEX IF NOT EXISTS idx_charging_data_charger ON public.charging_data(charger_name);
CREATE INDEX IF NOT EXISTS idx_charging_data_vcard ON public.charging_data(vcard);

-- 2. Station Owners Mapping Table
CREATE TABLE IF NOT EXISTS public.station_owners (
    charger_name TEXT PRIMARY KEY,
    phone_number TEXT DEFAULT ''
);

-- 3. Admin Users Table
CREATE TABLE IF NOT EXISTS public.admin_users (
    phone_number TEXT PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 4. Precomputed System Snapshots Table
CREATE TABLE IF NOT EXISTS public.system_snapshots (
    snapshot_key TEXT PRIMARY KEY,
    snapshot_data JSONB NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 5. Enable Row Level Security (RLS) & Public Read Policy
ALTER TABLE public.charging_data ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.station_owners ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.admin_users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.system_snapshots ENABLE ROW LEVEL SECURITY;

-- Allow anon read access (or customize according to auth needs)
CREATE POLICY "Allow public read charging_data" ON public.charging_data FOR SELECT USING (true);
CREATE POLICY "Allow public read station_owners" ON public.station_owners FOR SELECT USING (true);
CREATE POLICY "Allow public read admin_users" ON public.admin_users FOR SELECT USING (true);
CREATE POLICY "Allow public read system_snapshots" ON public.system_snapshots FOR SELECT USING (true);

